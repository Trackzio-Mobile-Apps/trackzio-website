export function regionsForCountry(countryName: string): readonly string[] {
  const country = getCountryByName(countryName);
  if (!country) return [];
  return REGIONS[country.code] ?? [];
}

export function matchRegion(regions: readonly string[], value: string): string {
  const needle = value.trim().toLowerCase();
  if (!needle) return "";
  return regions.find((region) => region.toLowerCase() === needle) ?? "";
}
