export function regionKeywords(countryName: string, regionName: string): string {
  const code = getCountryByName(countryName)?.code ?? "";
  const codes = REGION_CODES[code];
  if (!codes) return "";
  return Object.entries(codes)
    .filter(([, name]) => name === regionName)
    .map(([abbreviation]) => abbreviation)
    .join(" ");
}

export function regionsForCountry(countryName: string): readonly string[] {
  const country = getCountryByName(countryName);
  if (!country) return [];
  return REGIONS[country.code] ?? [];
}

export function matchRegion(regions: readonly string[], value: string, countryCode = ""): string {
  const needle = value.trim().toLowerCase();
  if (!needle) return "";
  const exact = regions.find((region) => region.toLowerCase() === needle);
  if (exact) return exact;

  const code = countryCode.trim().toUpperCase();
  const codes = code ? REGION_CODES[code] : undefined;
  if (!codes) return "";
  const suffix = value.trim().toUpperCase().split("-").pop() || "";
  const named = codes[suffix];
  return named && regions.includes(named) ? named : "";
}
